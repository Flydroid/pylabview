"""Build skeleton.ctl: a LabVIEW-saved standalone cluster typedef with its links stripped.

usage: python -m pylabview.ctlgen.make_skeleton <cluster typedef .ctl> <out>

The source must be a standalone (no LIBN) cluster type definition saved by the
LabVIEW version you want to target. Its link tables are emptied, optional
blocks are dropped and the VI tags (VITS) are reset to just
NI.LV.All.SourceOnly ("separate compiled code from source"), so nothing
specific to the source file is left besides fonts, icon and version info.
Everything type-related is regenerated by gen.py anyway.
"""
import struct
import sys
from pathlib import Path

from . import rsrc

# Empty link tables: u16 version 1, 4-char kind, u32 count 0, u16 3
NO_LINKS = {
    b"LIvi": b"\x00\x01LVCC\x00\x00\x00\x00\x00\x03",
    b"LIfp": b"\x00\x01FPHP\x00\x00\x00\x00\x00\x03",
    b"LIbd": b"\x00\x01BDHP\x00\x00\x00\x00\x00\x03",
    b"FPEx": b"\x00\x00\x00\x00",
}


def source_only_vits(lvsr_version: bytes) -> bytes:
    """VITS with the single tag NI.LV.All.SourceOnly = TRUE (bool variant), as LabVIEW writes it."""
    name = b"NI.LV.All.SourceOnly"
    # LV variant: version, 1 type (len 4: bool 0x21), ..., data byte 0x01 = TRUE
    variant = lvsr_version + bytes.fromhex("0000000100040021000100000100000000")
    return struct.pack(">I", 1) + struct.pack(">I", len(name)) + name + struct.pack(">I", len(variant)) + variant


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    base = rsrc.read(src.read_bytes())
    if base.block(b"LIBN") is not None:
        sys.exit("skeleton source must not be a library member")
    for ident, data in NO_LINKS.items():
        base.block(ident).sections[0].data = data
    lvsr = base.block(b"LVSR").sections[0]
    base.block(b"VITS").sections[0].data = source_only_vits(lvsr.data[:4])
    base.blocks = [b for b in base.blocks if b.ident not in (b"STR ", b"STRG", b"LIBN")]
    out.write_bytes(rsrc.write(base))
    print("wrote", out, [b.ident.decode() for b in base.blocks])


if __name__ == "__main__":
    main()
